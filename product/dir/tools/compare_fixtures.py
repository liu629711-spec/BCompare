#!/usr/bin/env python3
"""Run the M3 folder-comparison fixture corpus and check the recorded expectations.

    python D:\\Rea\\product\\dir\\tools\\compare_fixtures.py
    python D:\\Rea\\product\\dir\\tools\\compare_fixtures.py --verbose
    python D:\\Rea\\product\\dir\\tools\\compare_fixtures.py --case audit-trees-crc
    python D:\\Rea\\product\\dir\\tools\\compare_fixtures.py --json out.json

The runner drives the real engine through `product/dir`'s own CLI binary, parses
the report it produces, and compares the result against `fixtures/cases.json`.

# What is being asserted, and against what

`fixtures/cases.json` records expectations derived from the observed criteria
model (`product/docs/00-current-state.md` section 6) and from the shipped help
text plus the decompiled report writer. It is **not** a golden BC report: this
workspace has none (`product/verify/README.md` section 9), and this task is
forbidden from invoking the Oracle. So a pass here means "the engine still
produces the behaviour this task committed to", not "BC parity". The manifest
labels every case `observed` / `derived` / `predicted` so the distinction is not
lost.

# Oracle correspondence

Each case also emits the exact Beyond Compare script that would reproduce it, so
the project lead's serial Oracle pass can run the same corpus:

    load "<left>" "<right>"
    expand all
    folder-report layout:<layout> output-to:"<out>"

That recipe is the one verified in this workspace
(`product/verify/README.md` section 2).
"""

from __future__ import annotations

import argparse
import json
import os
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
DIR_CRATE = HERE.parent
FIXTURES = DIR_CRATE / "fixtures"
BINARY = DIR_CRATE / "target" / "debug" / ("reacmp-dir.exe" if os.name == "nt" else "reacmp-dir")

#: The read-only tree pair owned by `product/verify`, used by the `audit-trees`
#: cases. Referenced in place, never copied: it is read-only evidence.
AUDIT_TREES = pathlib.Path(r"D:\Rea\verify\dir\trees")

#: Fixed offset for rendering, so expectations do not depend on the host zone.
#: 480 = UTC+08:00, which is what the observed audit report was rendered in.
TZ_OFFSET = "480"


class CaseFailure(Exception):
    pass


def build_binary() -> None:
    result = subprocess.run(
        ["cargo", "build", "--quiet"],
        cwd=DIR_CRATE,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise SystemExit(
            "cargo build failed:\n" + result.stdout + "\n" + result.stderr
        )


def paths_for(pair: str) -> tuple[str, str, str]:
    """Return (left, right, note) for a pair name."""
    if pair == "verify-dir-trees":
        if not AUDIT_TREES.is_dir():
            raise CaseFailure(
                f"the read-only audit tree {AUDIT_TREES} is not present; "
                "the audit-trees cases cannot run"
            )
        return (
            str(AUDIT_TREES / "L"),
            str(AUDIT_TREES / "R"),
            "read-only fixture owned by product/verify",
        )
    left = FIXTURES / "trees" / pair / "L"
    right = FIXTURES / "trees" / pair / "R"
    if not left.is_dir() or not right.is_dir():
        raise CaseFailure(f"fixture tree missing: {left} or {right}")
    return str(left), str(right), "generated by tools/make_fixtures.py"



def summary_counts(statuses) -> dict[str, int]:
    """The summary labels the renderer emits for a set of status tokens."""
    label = {
        "same": "same",
        "diff": "different",
        "ltonly": "left only",
        "rtonly": "right only",
        "ltnewer": "left newer",
        "rtnewer": "right newer",
        "unknown": "unknown",
    }
    counts = {v: 0 for v in label.values()}
    for status in statuses:
        counts[label[status]] = counts.get(label[status], 0) + 1
    counts["total"] = sum(1 for _ in statuses)
    return counts


def parse_summary_counts(text: str) -> dict[str, int]:
    """Read the `label : count` body of a rendered summary report."""
    out: dict[str, int] = {}
    for line in text.splitlines():
        if ":" not in line:
            continue
        label, _, value = line.rpartition(":")
        label = label.strip()
        value = value.strip()
        if label and value.isdigit():
            out[label] = int(value)
    return out


def check_corpus_is_current(manifest: dict) -> list[str]:
    """Refuse to run a manifest that no longer matches its generators.

    Two independent staleness checks, both cheap:

    * the tree digests in `fixtures/tree-digests.json` must match the trees on
      disk (`make_fixtures.py --check`);
    * every `observed` case whose pair is `verify-dir-trees` must still agree with
      the stored Oracle report, read independently here.

    A stale corpus would let a passing run mean "the expectations were regenerated
    to match the engine", which is exactly the failure this project's evidence
    discipline exists to prevent.
    """
    problems: list[str] = []

    result = subprocess.run(
        [sys.executable, str(HERE / "make_fixtures.py"), "--check"],
        capture_output=True, text=True,
    )
    if result.returncode != 0:
        problems.append(
            "the tree corpus has drifted from its recorded digests:\n"
            + (result.stdout + result.stderr).strip()
        )

    # Regenerate the manifest in memory and compare the observed-anchor cases.
    probe = subprocess.run(
        [sys.executable, "-c",
         "import sys,json;sys.path.insert(0,r'%s');import make_cases as mc;"
         "cases,problems=mc.build_cases();"
         "print(json.dumps({'problems':problems,'observed':"
         "{c['id']:c['expected_statuses'] for c in cases if c['evidence']=='observed'}}))"
         % str(HERE)],
        capture_output=True, text=True,
    )
    if probe.returncode != 0:
        problems.append(f"could not re-derive the case set: {probe.stderr.strip()[:400]}")
        return problems
    try:
        fresh = json.loads(probe.stdout)
    except json.JSONDecodeError as exc:
        problems.append(f"could not parse the re-derived case set: {exc}")
        return problems

    if fresh["problems"]:
        problems.append(
            "the case generator reports problems: " + "; ".join(fresh["problems"][:4])
        )

    recorded_observed = {
        c["id"]: c["expected_statuses"] for c in manifest["cases"] if c["evidence"] == "observed"
    }
    fresh_observed = fresh["observed"]
    if recorded_observed != fresh_observed:
        changed = sorted(
            k for k in set(recorded_observed) | set(fresh_observed)
            if recorded_observed.get(k) != fresh_observed.get(k)
        )
        problems.append(
            "the recorded `observed` expectations no longer match the artifacts they "
            f"are anchored to: regenerate with tools/make_cases.py (changed: {changed})"
        )
    return problems


def oracle_script(left: str, right: str, layout: str, out_path: str) -> str:
    """The verified Oracle recipe for this case (product/verify/README.md §2)."""
    return (
        f'load "{left}" "{right}"\n'
        f"expand all\n"
        f'folder-report layout:{layout} output-to:"{out_path}"\n'
    )


def run_case(binary: pathlib.Path, case: dict, verbose: bool) -> tuple[bool, str, str]:
    """Run one case; return (passed, detail, raw_report)."""
    left, right, _ = paths_for(case["pair"])
    layout = case["layout"]
    expected_exit = case["expected_exit"]

    argv = [
        str(binary),
        "--criteria", case["criteria"],
        "--layout", layout,
        "--tz-offset", TZ_OFFSET,
        "--print-exit-code",
    ]
    # A case may exercise the CLI flag form of a criteria instead of the criteria
    # string (recorded in the manifest's `extra.cli_flag`).
    cli_flag = (case.get("extra") or {}).get("cli_flag")
    if cli_flag:
        argv.append(cli_flag)
    argv += [left, right]

    result = subprocess.run(argv, capture_output=True, text=True, encoding="utf-8")
    if result.returncode != expected_exit:
        return (
            False,
            f"exit {result.returncode} != expected {expected_exit}; "
            f"stderr={result.stderr.strip()[:300]}",
            result.stdout,
        )

    if case["expected_error"] is not None:
        # A rejection case: assert the error class, and that no report was written.
        needle = {
            "invalid_criteria": "invalid folder-compare criteria",
            "not_probed": "not been probed",
            "unknown_layout": "unknown report layout",
        }.get(case["expected_error"], "")
        if needle and needle not in result.stderr:
            return False, f"stderr did not mention {needle!r}: {result.stderr.strip()[:300]}", ""
        if case["criteria"] not in ("html", "interleaved", "csv", "text") and layout == "xml":
            # A rejected criteria must produce no report at all.
            if "<bcreport" in result.stdout:
                return False, "a rejected criteria still produced a report", result.stdout
        return True, f"rejected as expected ({case['expected_error']})", ""

    if case["expected_statuses"] is None or not case["expected_statuses"]:
        return True, "ran, no status assertion", result.stdout

    if layout == "summary":
        # The summary layout reports counts, not names, so the assertion is on the
        # counts implied by the expected statuses.
        expected_counts = summary_counts(case["expected_statuses"].values())
        actual_counts = parse_summary_counts(result.stdout)
        problems = []
        for label, want in expected_counts.items():
            got = actual_counts.get(label)
            if got != want:
                problems.append(f"{label}: expected {want}, got {got}")
        if problems:
            return False, "; ".join(problems), result.stdout
        return True, f"summary counts matched {expected_counts}", result.stdout

    if layout != "xml":
        # The side-by-side layout is structurally unobserved
        # (product/verify/README.md section 9), so the only assertable property is
        # that every expected entry name appears. Names are taken as literals from
        # the manifest (unescaped), which is what a text layout prints.
        missing = [
            name for name in case["expected_statuses"]
            if name.split("/")[-1] not in result.stdout
        ]
        if missing:
            return False, f"text layout is missing these names: {missing[:8]}", result.stdout
        return True, f"text layout named all {len(case['expected_statuses'])} entry/entries", result.stdout

    actual = extract_statuses(result.stdout)
    expected = case["expected_statuses"]
    problems = []
    for path, want in expected.items():
        got = actual.get(path)
        if got is None:
            problems.append(f"{path}: missing from the report (expected {want})")
        elif got != want:
            problems.append(f"{path}: expected {want}, got {got}")
    if problems:
        return False, "; ".join(problems[:6]) + (f" (+{len(problems)-6} more)" if len(problems) > 6 else ""), result.stdout
    return True, f"{len(expected)} row(s) matched", result.stdout


def unescape_xml(text: str) -> str:
    """Reverse the writer's escaping so a name can be compared to the manifest.

    The manifest records literal names, while the report escapes `&` as `&amp;`
    (observed as necessary: an unescaped `&` would make the report unparseable).
    Without this, `amp&name.txt` looks "missing from the report".
    """
    return (
        text.replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&quot;", '"')
        .replace("&apos;", "'")
        # `&amp;` last, so `&amp;lt;` unescapes to `&lt;` rather than `<`.
        .replace("&amp;", "&")
    )


def extract_statuses(xml: str) -> dict[str, str]:
    """Read {relative path: status} from a folder-report XML.

    `filecomp` rows carry an explicit `status` attribute (observed:
    `tools/_audit/dir-load-expand-report.xml`). `foldercomp` rows (directories) do
    **not** — the observed report has no status on a directory element — so a
    directory's status is reproduced here from the two facts the report does
    carry:

    * whether both a `<lt>` and an `<rt>` block are present (a one-sided
      directory is an orphan): this is the observed way the report distinguishes
      `ltonly`/`rtonly`, since the missing side's element is omitted entirely;
    * the aggregate of its children.

    That rule mirrors `crate::tree::directory_status` in the engine, so the
    assertion is on the report's *content* rather than on a re-implementation
    that could drift.
    """
    stack: list[dict] = []
    root_open = False
    top: list[dict] = []

    for line in xml.splitlines():
        s = line.strip()
        if s == "<foldercomp>":
            if not root_open:
                root_open = True
                continue
            stack.append({"kind": "dir", "name": "", "children": [], "sides": set()})
            continue
        if s == "</foldercomp>":
            if not stack:
                continue
            entry = stack.pop()
            (stack[-1]["children"] if stack else top).append(entry)
            continue
        m = re.match(r"<name>(.*)</name>$", s)
        if m and stack:
            stack[-1]["name"] = unescape_xml(m.group(1))
            continue
        if s in ("<lt>", "<rt>"):
            for entry in stack:
                entry["sides"].add(s[1:3])
            continue
        m = re.match(r'<filecomp status="([a-z]+)">$', s)
        if m:
            stack.append({
                "kind": "file", "name": "", "status": m.group(1),
                "children": [], "sides": set(),
            })
            continue
        if s == "</filecomp>":
            if not stack:
                continue
            entry = stack.pop()
            (stack[-1]["children"] if stack else top).append(entry)
            continue

    out: dict[str, str] = {}

    def status_of(entry: dict) -> str:
        if entry["kind"] == "file":
            return entry["status"] or "unknown"
        sides = entry["sides"]
        if sides and sides != {"lt", "rt"}:
            # A directory present on one side only.
            return "ltonly" if sides == {"lt"} else "rtonly"
        child_statuses = [status_of(c) for c in entry["children"]]
        if any(s != "same" for s in child_statuses):
            return "diff"
        return "same"

    def emit(entry: dict, prefix: str) -> None:
        path = f"{prefix}/{entry['name']}" if prefix else entry["name"]
        out[path] = status_of(entry)
        for child in entry["children"]:
            emit(child, path)

    for entry in top:
        emit(entry, "")
    return out


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--case", action="append", help="run only this case id")
    parser.add_argument("--verbose", "-v", action="store_true")
    parser.add_argument("--json", help="write a machine-readable result payload here")
    parser.add_argument("--emit-reports", help="write each case's raw report into this directory")
    parser.add_argument("--no-build", action="store_true")
    parser.add_argument(
        "--skip-staleness-check", action="store_true",
        help="run even when the corpus or its expectations have drifted (default: refuse)",
    )
    args = parser.parse_args(argv)

    if not args.no_build:
        build_binary()
    if not BINARY.is_file():
        raise SystemExit(f"binary not found: {BINARY}; run without --no-build")

    manifest = json.loads((FIXTURES / "cases.json").read_text(encoding="utf-8"))

    if not args.skip_staleness_check:
        stale = check_corpus_is_current(manifest)
        if stale:
            for line in stale:
                print(f"STALE: {line}", file=sys.stderr)
            print(
                "\nRefusing to run: the corpus or its expectations no longer match the "
                "artifacts they came from. Re-run tools/make_fixtures.py and "
                "tools/make_cases.py, or pass --skip-staleness-check to override.",
                file=sys.stderr,
            )
            return 2

    cases = manifest["cases"]
    if args.case:
        wanted = set(args.case)
        cases = [c for c in cases if c["id"] in wanted]
        missing = wanted - {c["id"] for c in cases}
        if missing:
            raise SystemExit(f"no such case id(s): {sorted(missing)}")

    reports_dir = pathlib.Path(args.emit_reports) if args.emit_reports else None
    if reports_dir:
        reports_dir.mkdir(parents=True, exist_ok=True)

    passed = 0
    failed: list[tuple[str, str]] = []
    records = []

    for case in cases:
        try:
            ok, detail, raw = run_case(BINARY, case, args.verbose)
        except CaseFailure as exc:
            ok, detail, raw = False, str(exc), ""
        except Exception as exc:  # noqa: BLE001 - report the failure, keep going
            ok, detail, raw = False, f"{type(exc).__name__}: {exc}", ""

        records.append({
            "id": case["id"],
            "pair": case["pair"],
            "criteria": case["criteria"],
            "layout": case["layout"],
            "evidence": case["evidence"],
            "expected_exit": case["expected_exit"],
            "expected_error": case["expected_error"],
            "expected_statuses": case["expected_statuses"],
            "oracle_script": (
                None if case["expected_error"] is not None
                else oracle_script(*paths_for(case["pair"])[:2], case["layout"],
                                   f"<out-{case['id']}.xml>")
            ),
            "passed": ok,
            "detail": detail,
        })

        if reports_dir and raw:
            (reports_dir / f"{case['id']}.{ 'xml' if case['layout']=='xml' else 'txt' }").write_text(
                raw, encoding="utf-8", newline=""
            )

        if ok:
            passed += 1
            if args.verbose:
                print(f"PASS {case['id']:<52} [{case['evidence']:<9}] {detail}")
        else:
            failed.append((case["id"], detail))
            print(f"FAIL {case['id']:<52} [{case['evidence']:<9}] {detail}")

    total = len(cases)
    print()
    print(f"cases: {total}  passed: {passed}  failed: {len(failed)}")
    by_grade: dict[str, list[int]] = {}
    for rec in records:
        slot = by_grade.setdefault(rec["evidence"], [0, 0])
        slot[0] += 1
        if rec["passed"]:
            slot[1] += 1
    for grade in sorted(by_grade):
        n, ok = by_grade[grade]
        print(f"  {grade:<9} {ok}/{n}")

    if args.json:
        payload = {
            "binary": str(BINARY),
            "case_count": total,
            "passed": passed,
            "failed": len(failed),
            "by_evidence_grade": {
                g: {"total": v[0], "passed": v[1]} for g, v in sorted(by_grade.items())
            },
            "records": records,
            "honesty_boundary": manifest["honesty_boundary"],
        }
        pathlib.Path(args.json).write_text(
            json.dumps(payload, indent=1, ensure_ascii=False) + "\n",
            encoding="utf-8",
            newline="\n",
        )
        print(f"wrote {args.json}")

    if failed:
        print()
        print("failures:")
        for cid, detail in failed:
            print(f"  {cid}: {detail}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
