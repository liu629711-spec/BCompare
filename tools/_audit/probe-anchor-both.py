"""Re-run the full 45-anchor corpus against BOTH installs, honouring options.

The golden corpus (verify/golden) was generated by tools/bc-anchor-suite.py and
its README attributes it to "BCompare 5.2.6 / BComp.com". The declared project
target is a different binary (5.2.1.32035). This probe answers, with evidence:

  Q1. Do the two installs produce the SAME status sequences on all 45 anchors?
  Q2. Does the CURRENT install reproduce the golden bytes (modulo the volatile
      `created=` timestamp)?

Options are recovered from each manifest entry's `note` field ("options:<name>").

Inputs are referenced by the exact paths golden used so the XML filename1/
filename2 fields match; only report output is redirected under tools/_audit.
"""
from __future__ import annotations

import json
import pathlib
import re
import subprocess

AUDIT = pathlib.Path(r"D:\Rea\tools\_audit")
OUT = AUDIT / "anchors"
GOLD = pathlib.Path(r"D:\Rea\verify\golden")

INSTALLS = {
    "current-5.2.1.32035": r"D:\BCompare\BCompare\BComp.com",
    "stale-5.2.6.32774": r"D:\bc-official\app\BComp.com",
}


def option_of(note: str) -> str | None:
    m = re.search(r"options:([A-Za-z0-9+\-]+)", note or "")
    return m.group(1) if m else None


def statuses(xml: str) -> list[str]:
    return re.findall(r'<linecomp status="([a-z]+)"', xml)


def strip_volatile(xml: str) -> str:
    return re.sub(r'created="[^"]*"', 'created="<T>"', xml)


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    script = AUDIT / "_anchor-script.txt"
    man = json.loads((GOLD / "manifest.json").read_text(encoding="utf-8"))

    per_install: dict[str, dict[str, tuple[bool, bool]]] = {k: {} for k in INSTALLS}

    for inst, exe in INSTALLS.items():
        for name, info in man.items():
            lp = pathlib.Path(info["left"])
            rp = pathlib.Path(info["right"])
            if not lp.exists() or not rp.exists():
                continue
            opt = option_of(info.get("note", ""))
            opt_part = f" options:{opt}" if opt else ""
            script.write_text(
                f'text-report layout:xml{opt_part} output-to:"%3" "%1" "%2"\n',
                encoding="utf-8")
            outp = OUT / f"{inst}-{name}.xml"
            cp = subprocess.run(
                [exe, "/silent", f"@{script}", str(lp), str(rp), str(outp)],
                capture_output=True, timeout=180)
            got = outp.read_text(encoding="utf-8", errors="replace") if outp.exists() else ""
            want = pathlib.Path(info["report"]).read_text(encoding="utf-8", errors="replace")
            status_ok = statuses(got) == info["statuses"] == statuses(want)
            byte_ok = strip_volatile(got) == strip_volatile(want)
            per_install[inst][name] = (status_ok, byte_ok)

    a, b = per_install["current-5.2.1.32035"], per_install["stale-5.2.6.32774"]
    common = sorted(set(a) & set(b))

    status_agree = [n for n in common if a[n][0] == b[n][0] == True]
    byte_cur = [n for n in common if a[n][1]]
    byte_stale = [n for n in common if b[n][1]]
    status_lost_cur = [n for n in common if b[n][0] and not a[n][0]]
    status_lost_stale = [n for n in common if a[n][0] and not b[n][0]]

    print(f"anchors compared: {len(common)}")
    print()
    print(f"status sequence == golden           current={len(status_agree)}/{len(common)}"
          f"  (stale identical on same set: "
          f"{sum(1 for n in status_agree if b[n][0])}/{len(common)})")
    print(f"byte-identical XML vs golden        current={len(byte_cur)}/{len(common)}")
    print(f"                                    stale  ={len(byte_stale)}/{len(common)}")
    print()
    print(f"statuses reproduced by stale but NOT current : {status_lost_cur}")
    print(f"statuses reproduced by current but NOT stale : {status_lost_stale}")
    if byte_stale:
        print(f"anchors stale matches byte-wise but current does not: "
              f"{sorted(set(byte_stale) - set(byte_cur))}")
    (OUT / "summary.json").write_text(json.dumps(
        {k: {n: {"status_ok": v[0], "byte_ok": v[1]} for n, v in d.items()}
         for k, d in per_install.items()}, indent=1), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
